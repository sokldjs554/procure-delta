"""Generate the static demo's allowlisted snapshot from the same artifacts as the API."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps/api"))


def main() -> None:
    from app.evaluation.summary import read_published_summary

    result = read_published_summary(ROOT / "apps/api/app/evaluation/results")
    target = ROOT / "apps/web/lib/evaluation-snapshot.ts"
    payload = json.dumps(result.model_dump(mode="json"), ensure_ascii=False, indent=2)
    target.write_text(
        '// Generated by scripts/publish_evaluation_snapshot.py. Do not edit metrics.\n'
        'import type { EvaluationSummary } from "./api";\n\n'
        f'export const evaluationSnapshot: EvaluationSummary = {payload};\n',
        encoding="utf-8",
    )
    print(f"Published allowlisted evaluation snapshot: {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
